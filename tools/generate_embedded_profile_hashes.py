#!/usr/bin/env python3
"""Generate the embedded qualification profile digest bindings."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
PROFILES = {
    "RETRY_2": "test-direct-sample-retry-2-nnpsk0.json",
    "MULTI_PEER": "test-direct-multi-peer-nnpsk0.json",
}
HEADER = ROOT / "tests/embedded/espnow_dmp/profile_hashes.h"
PYTHON = ROOT / "tests/embedded/espnow_dmp/profile_hashes.py"


def outputs() -> dict[Path, str]:
    hashes = {
        key: hashlib.sha256((ROOT / "profiles/deployments" / name).read_bytes()).hexdigest()
        for key, name in PROFILES.items()
    }
    rows = ["/* Generated by tools/generate_embedded_profile_hashes.py. */",
            "#ifndef DMP_QUAL_PROFILE_HASHES_H", "#define DMP_QUAL_PROFILE_HASHES_H",
            "", "#include <stdint.h>", ""]
    for key, value in hashes.items():
        label = key.replace("_", " ").title()
        rows.append(f"#define DMP_{key}_PROFILE_HASH_HEX \"{value}\"")
        rows.append(f"static const uint8_t DMP_{key}_PROFILE_HASH_BYTES[32] = {{")
        bytes_ = [f"0x{value[i:i + 2]}U" for i in range(0, 64, 2)]
        for i in range(0, 32, 8):
            suffix = "," if i + 8 < 32 else ""
            rows.append("    " + ", ".join(bytes_[i:i + 8]) + suffix)
        rows.append("};")
        rows.append("")
    rows.extend(["#endif", ""])
    python = "# Generated by tools/generate_embedded_profile_hashes.py.\n" + "".join(
        f'{key}_PROFILE_HASH = "{value}"\n' for key, value in hashes.items())
    return {HEADER: "\n".join(rows), PYTHON: python}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("stale generated profile digest files: " + ", ".join(str(p.relative_to(ROOT)) for p in stale),
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
